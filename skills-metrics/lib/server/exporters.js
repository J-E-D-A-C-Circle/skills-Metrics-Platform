// =============================================================================
// exporters.js · Turns a finished report (lib/server/reports.js runReport) into an Excel, PDF or CSV file
// Screen / URL: Reports > Export Excel / PDF / CSV (GET /api/reports/:key/export?format=xlsx|pdf|csv)
// Used by: app/api/reports/[key]/export/route.js, tests/reports.test.js   Depends on: xlsx, pdfkit, lib/server/reports.js
// Sections (search for these markers): EXPORT · Formats, EXPORT · CSV, EXPORT · Excel, EXPORT · PDF layout,
//   EXPORT · PDF table, EXPORT · PDF footer
// Every file is written from the same rows, columns and summary as the on-screen table, so the numbers always
// match. Averages are written as numbers rounded to 2 decimals (the classification was already made on the
// unrounded value); a missing result is written as "Not assessed", never 0.
// =============================================================================
import 'server-only';
import * as XLSX from 'xlsx';
import PDFDocument from 'pdfkit';
import { cellText, isNumeric } from './reports';

// ===== EXPORT · Formats =====
export const FORMATS = {
  xlsx: { mime: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', ext: 'xlsx' },
  pdf: { mime: 'application/pdf', ext: 'pdf' },
  csv: { mime: 'text/csv; charset=utf-8', ext: 'csv' },
};
export const fileName = (rep, format) => 'dvla-' + rep.report.key + '-report-' + rep.generatedAt.slice(0, 10) + '.' + FORMATS[format].ext;
const fmtGenerated = iso => new Date(iso).toLocaleString('en-GB', { day: 'numeric', month: 'long', year: 'numeric', hour: '2-digit', minute: '2-digit', timeZone: 'UTC' }) + ' GMT';

// ===== EXPORT · CSV =====
// UTF-8 with a byte-order mark so Excel opens names correctly. Plain table: one header row, then the rows.
const csvCell = v => { const s = String(v ?? ''); return /[",\r\n]/.test(s) || /^[=+\-@]/.test(s) ? '"' + (/^[=+\-@]/.test(s) ? "'" : '') + s.replace(/"/g, '""') + '"' : s; };
export function toCsv(rep) {
  const lines = [rep.columns.map(c => csvCell(c.label)).join(',')];
  for (const r of rep.rows) lines.push(rep.columns.map(c => csvCell(cellText(c, r[c.key]))).join(','));
  return Buffer.from('﻿' + lines.join('\r\n') + '\r\n', 'utf8');
}

// ===== EXPORT · Excel =====
// Sheet "Report": the table (numbers stay numbers, with 2-decimal formats). Sheet "About this report": title,
// generated by / on, filters used, summary and notes.
const XL_FORMAT = { avg: '0.00', num: '0.00', int: '0', pct: '0.0"%"' };
export function xlsxValue(c, v) {
  if (v == null || v === '') return c.empty || '';
  if (isNumeric(c)) return Number(v);
  return cellText(c, v);
}
export function toXlsx(rep) {
  const aoa = [rep.columns.map(c => c.label), ...rep.rows.map(r => rep.columns.map(c => xlsxValue(c, r[c.key])))];
  const ws = XLSX.utils.aoa_to_sheet(aoa);
  rep.columns.forEach((c, j) => {
    const z = XL_FORMAT[c.type]; if (!z) return;
    for (let i = 1; i < aoa.length; i++) { const cell = ws[XLSX.utils.encode_cell({ r: i, c: j })]; if (cell && cell.t === 'n') cell.z = z; }
  });
  ws['!cols'] = rep.columns.map((c, j) => ({ wch: Math.min(60, Math.max(8, ...aoa.slice(0, 500).map(r => String(r[j] ?? '').length + 2))) }));
  if (rep.rows.length) ws['!autofilter'] = { ref: ws['!ref'] };
  const about = XLSX.utils.aoa_to_sheet([
    [rep.report.title], [rep.report.description], [],
    ['Generated by', rep.generatedBy], ['Generated on', fmtGenerated(rep.generatedAt)], ['Rows', rep.total], [],
    ['Filters used'], ...(rep.filtersUsed.length ? rep.filtersUsed : [['None', '']]), [],
    ['Summary'], ...rep.summary.map(s => [s.label, String(s.value), s.sub || '']), [],
    ...(rep.notes.length ? [['Notes'], ...rep.notes.map(n => [n])] : []),
    ['Source', 'DVLA Skill Matrix & Assessment Platform. Final averages are the average of all completed attempts; missing results are "Not assessed", never 0.'],
  ]);
  about['!cols'] = [{ wch: 26 }, { wch: 70 }, { wch: 40 }];
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, 'Report');
  XLSX.utils.book_append_sheet(wb, about, 'About this report');
  wb.Props = { Title: rep.report.title, Author: 'DVLA Skill Matrix', CreatedDate: new Date(rep.generatedAt) };
  return XLSX.write(wb, { type: 'buffer', bookType: 'xlsx', compression: true });
}

// ===== EXPORT · PDF layout =====
// A4 landscape. Dark green (#054218) title bar only; the rest is black and grey on white. Long reports are cut
// at PDF_MAX_ROWS rows with a note pointing to the Excel export (which always holds every row).
export const PDF_MAX_ROWS = 3000;
const BRAND = '#054218', INK = '#111827', MUTED = '#6b7280', LINE = '#e5e7eb', HEAD_BG = '#f3f4f6';
// The built-in PDF fonts only cover Western European characters; anything else becomes "?" instead of garbage.
const safe = s => String(s ?? '').replace(/[→]/g, '->').replace(/[–—]/g, '-').replace(/…/g, '...').replace(/[÷]/g, '/').replace(/[^\x09\x0a\x0d\x20-\x7e -ÿ‘’“”•]/g, '?');

export function toPdf(rep) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margins: { top: 36, bottom: 44, left: 30, right: 30 }, bufferPages: true,
      info: { Title: safe(rep.report.title), Author: 'DVLA Skill Matrix & Assessment Platform', Subject: safe(rep.report.description) } });
    const chunks = [];
    doc.on('data', c => chunks.push(c)); doc.on('end', () => resolve(Buffer.concat(chunks))); doc.on('error', reject);
    const W = doc.page.width, L = 30, CW = W - 60, bottom = () => doc.page.height - 44;

    // Title bar and the details block under it.
    doc.rect(0, 0, W, 62).fill(BRAND);
    doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(17).text(safe(rep.report.title), L, 16, { width: CW, lineBreak: false });
    doc.font('Helvetica').fontSize(9).text('DVLA Skill Matrix & Assessment Platform', L, 40, { width: CW, lineBreak: false });
    let y = 76;
    const line = (label, value) => {
      doc.font('Helvetica-Bold').fontSize(8.5).fillColor(INK).text(safe(label) + ': ', L, y, { continued: true }).font('Helvetica').fillColor('#374151').text(safe(value), { width: CW });
      y = doc.y + 2;
    };
    doc.font('Helvetica').fontSize(8.5).fillColor(MUTED).text(safe(rep.report.description), L, y, { width: CW }); y = doc.y + 6;
    line('Generated by', rep.generatedBy + ' on ' + fmtGenerated(rep.generatedAt));
    line('Filters used', rep.filtersUsed.length ? rep.filtersUsed.map(([k, v]) => k + ': ' + v).join(' · ') : 'None');
    if (rep.summary.length) line('Summary', rep.summary.map(s => s.label + ': ' + s.value + (s.sub ? ' (' + s.sub + ')' : '')).join(' · '));
    rep.notes.forEach(n => line('Note', n));
    const rows = rep.rows.slice(0, PDF_MAX_ROWS);
    line('Rows', rep.total + (rep.total > rows.length ? ' (the first ' + rows.length + ' are shown here; the Excel export holds every row)' : ''));
    y += 8;

    // ===== EXPORT · PDF table =====
    // Column widths are measured from the header and the first 300 rows: never narrower than the longest single
    // word (so "DEMO-0004" or "4.00" never break), and the spare width goes to the columns with longer text.
    const cols = rep.columns, text = rows.map(r => cols.map(c => safe(cellText(c, r[c.key])))), PAD = 3;
    const FS = cols.length > 11 ? 6.8 : 7.6;
    const measure = (s, bold) => doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(FS).widthOfString(s) + PAD * 2 + 1;
    const sample = text.slice(0, 300);
    const minW = cols.map((c, j) => Math.max(...safe(c.label).split(/\s+/).map(w => measure(w, true)), ...sample.map(t => Math.max(...t[j].split(/\s+/).map(w => measure(w, false))))));
    const prefW = cols.map((c, j) => Math.min(170, Math.max(minW[j], ...sample.map(t => measure(t[j], false)))));
    const sumMin = minW.reduce((a, b) => a + b, 0), extra = prefW.reduce((a, b, j) => a + (b - minW[j]), 0);
    const widths = sumMin >= CW ? minW.map(w => (w / sumMin) * CW)
      : minW.map((w, j) => w + (extra > 0 ? ((prefW[j] - w) / extra) * Math.min(extra, CW - sumMin) : 0) + (extra < CW - sumMin ? (CW - sumMin - extra) / cols.length : 0));
    const heightOf = (vals, bold) => { doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(FS); return Math.max(...vals.map((v, j) => doc.heightOfString(v || ' ', { width: widths[j] - PAD * 2 }))) + PAD * 2; };
    const drawRow = (vals, rowY, h, bold, bg) => {
      if (bg) doc.rect(L, rowY, CW, h).fill(bg);
      let x = L;
      vals.forEach((v, j) => {
        doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(FS).fillColor(bold ? '#374151' : INK)
          .text(v, x + PAD, rowY + PAD, { width: widths[j] - PAD * 2, align: isNumeric(cols[j]) ? 'right' : 'left' });
        x += widths[j];
      });
      doc.moveTo(L, rowY + h).lineTo(L + CW, rowY + h).lineWidth(0.5).strokeColor(LINE).stroke();
    };
    const head = cols.map(c => safe(c.label)), headH = heightOf(head, true);
    const header = () => { drawRow(head, y, headH, true, HEAD_BG); y += headH; };
    if (!rows.length) {
      doc.font('Helvetica').fontSize(10).fillColor(MUTED).text('No records match the filters used.', L, y + 10, { width: CW });
    } else {
      if (y + headH + 20 > bottom()) { doc.addPage(); y = 36; }
      header();
      text.forEach((vals, i) => {
        const h = heightOf(vals, false);
        if (y + h > bottom()) { doc.addPage(); y = 36; header(); }
        drawRow(vals, y, h, false, i % 2 ? '#fafafa' : null);
        y += h;
      });
    }

    // ===== EXPORT · PDF footer =====
    // Page numbers on every page. The bottom margin is lifted while writing so pdfkit doesn't add a new page.
    const range = doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i++) {
      doc.switchToPage(i);
      const m = doc.page.margins.bottom; doc.page.margins.bottom = 0;
      const fy = doc.page.height - 28;
      doc.font('Helvetica').fontSize(7.5).fillColor(MUTED);
      doc.text(safe(rep.report.title + ' · Generated ' + fmtGenerated(rep.generatedAt) + ' · Confidential: contains staff results'), L, fy, { width: CW * 0.75, lineBreak: false });
      doc.text('Page ' + (i - range.start + 1) + ' of ' + range.count, L + CW * 0.75, fy, { width: CW * 0.25, align: 'right', lineBreak: false });
      doc.page.margins.bottom = m;
    }
    doc.end();
  });
}
